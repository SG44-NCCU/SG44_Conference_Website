type ScheduleRow = [string, string, string, string, string, number, number, string, string]

export const importSessionsEndpoint = async (req: PayloadRequest) => {
  const { payload, user } = req

  if (!user || user.role !== 'admin') {
    return Response.json({ error: 'Forbidden. Admin access required.' }, { status: 403 })
  }

  try {
    // 1. 先刪除現有的 sessions（重新匯入）
    const existing = await payload.find({
      collection: 'sessions',
      limit: 1000,
    })
    for (const session of existing.docs) {
      await payload.delete({ collection: 'sessions', id: session.id })
    }

    // 2. 將資料依 session（同日期+場次名稱+廳別+時段）分組
    const sessionMap = new Map<string, {
      date: '2026-08-20' | '2026-08-21'
      timeRange: string
      room: string
      title: string
      chairName: string
      papers: Array<{ order: number; abstractId: number; paperTitle: string; presenterName: string }>
    }>()

    for (const row of SCHEDULE_DATA as unknown as ScheduleRow[]) {
      const [dateStr, timeRange, room, sessionTitle, chairName, order, abstractId, paperTitle, presenterName] = row
      const key = `${dateStr}|${sessionTitle}|${room}|${timeRange}`

      if (!sessionMap.has(key)) {
        // 轉換日期
        const date = (dateStr.includes('20日') ? '2026-08-20' : '2026-08-21') as '2026-08-20' | '2026-08-21'
        sessionMap.set(key, {
          date,
          timeRange,
          room,
          title: sessionTitle,
          chairName,
          papers: [],
        })
      }

      sessionMap.get(key)!.papers.push({ order, abstractId, paperTitle, presenterName })
    }

    // 3. 建立 Sessions
    const created: string[] = []
    for (const [, sessionData] of sessionMap) {
      const [startTime, endTime] = sessionData.timeRange.split('–').map((t: string) => t.trim())

      // 嘗試找到對應的 abstract
      const papersWithRefs = await Promise.all(
        sessionData.papers.map(async (p) => {
          // 嘗試找到對應的 abstract by id
          let abstractRef: number | null = null
          try {
            const found = await payload.findByID({
              collection: 'abstracts',
              id: p.abstractId,
            })
            if (found) abstractRef = p.abstractId
          } catch (_e) {
            // Abstract not found, use override
          }

          return {
            presentationOrder: p.order,
            abstract: abstractRef,
            abstractIdOverride: abstractRef ? undefined : p.abstractId,
            titleOverride: p.paperTitle,
            presenterName: p.presenterName,
          }
        }),
      )

      const session = await payload.create({
        collection: 'sessions',
        data: {
          title: sessionData.title,
          date: sessionData.date,
          startTime,
          endTime,
          room: sessionData.room,
          chairName: sessionData.chairName,
          type: 'oral',
          papers: papersWithRefs,
        },
      })

      created.push(`${session.id}: ${sessionData.title} (${sessionData.date}, ${sessionData.room})`)
    }

    return Response.json({
      success: true,
      message: `成功匯入 ${created.length} 個場次`,
      sessions: created,
    })
  } catch (error) {
    console.error('Error importing sessions:', error)
    return Response.json({ error: `匯入失敗: ${error}` }, { status: 500 })
  }
}
